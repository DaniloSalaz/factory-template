// Writes src/gen/routeSecurity.ts: what each operation of the contract requires, read
// from its `security` as the API's routegen reads it (api/tools/routegen). The
// fetcher sends X-Tenant-ID only to the operations that require a tenant.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const specPath = new URL("../../api-spec/openapi.gen.yaml", import.meta.url);
const outPath = new URL("../src/gen/routeSecurity.ts", import.meta.url);

type Requirement = Record<string, string[]>;
type Operation = { security?: Requirement[] };
type Spec = {
  security?: Requirement[];
  paths: Record<string, Record<string, Operation | unknown>>;
};

const methods = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

function security(where: string, sec: Requirement[]): { session: boolean; tenant: boolean } {
  if (sec.length === 0) {
    return { session: false, tenant: false };
  }
  const [req, ...rest] = sec;
  if (!req || rest.length > 0) {
    throw new Error(`${where}: alternative security requirements are not supported`);
  }
  const schemes = Object.keys(req);
  if (schemes.length === 0) {
    throw new Error(`${where}: an empty requirement is ambiguous; declare \`security: []\``);
  }
  const unknown = schemes.filter((s) => s !== "session" && s !== "tenant");
  if (unknown.length > 0) {
    throw new Error(`${where}: unknown security scheme ${unknown.join(", ")}`);
  }
  const result = { session: schemes.includes("session"), tenant: schemes.includes("tenant") };
  if (result.tenant && !result.session) {
    throw new Error(`${where}: a tenant requires a session`);
  }
  return result;
}

const spec = parse(readFileSync(specPath, "utf8")) as Spec;
if (!spec.security) {
  throw new Error("the contract must declare a root `security`");
}
const lines: string[] = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of methods) {
    const op = item[method] as Operation | undefined;
    if (!op) {
      continue;
    }
    const key = `${method.toUpperCase()} ${path}`;
    const s = security(key, op.security ?? spec.security);
    lines.push(`  ${JSON.stringify(key)}: { session: ${s.session}, tenant: ${s.tenant} },`);
  }
}

writeFileSync(
  outPath,
  `// Generated by scripts/gen-route-security.ts from api-spec/openapi.gen.yaml. Do not edit.

/** What each operation requires, keyed by "METHOD /path/{param}" as in the contract. */
export const routeSecurity: Readonly<Record<string, { session: boolean; tenant: boolean }>> = {
${lines.join("\n")}
};
`,
);
