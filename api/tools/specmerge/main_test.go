const appSpec = `openapi: 3.1.0
info: {title: App, version: 0.1.0}
tags:
  - name: appointments
paths:
  /appointments:
    get:
      operationId: listAppointments
      tags: [appointments]
      responses:
        "200": {description: ok, content: {application/json: {schema: {$ref: "#/components/schemas/Appointment"}}}}
        "500": {$ref: "core.yaml#/components/responses/InternalError"}
components:
  schemas:
    Appointment:
      type: object
      properties:
        problem: {$ref: "core.yaml#/components/schemas/Problem"}
  parameters:
    Page: {name: page, in: query, schema: {type: integer}}
`

func modules() []module {
	return []module{
		{name: "identity", zone: zoneCore, config: "core/identity/codegen.yaml"},
		{name: "appointments", zone: zoneApp, config: "app/modules/appointments/codegen.yaml"},
	}
}

func mergeStrings(t *testing.T, app string, mods []module) ([]byte, error) {
	t.Helper()
	return merge(source{name: "core.yaml", data: []byte(coreSpec)}, source{name: "app.yaml", data: []byte(app)}, mods)
}

func decode(t *testing.T, b []byte) map[string]any {
	t.Helper()
	var v map[string]any
	if err := yaml.Unmarshal(b, &v); err != nil {
		t.Fatalf("decode: %v", err)
	}
	return v
}

func TestMerge(t *testing.T) {
	t.Parallel()

	out, err := mergeStrings(t, appSpec, modules())
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(out, []byte("# Code generated by specmerge from api-spec/core.yaml and api-spec/app.yaml. DO NOT EDIT.\n")) {
		t.Errorf("missing header:\n%s", out)
	}
	s := string(out)
	// Core first, in its order, then the app.
	for _, order := range [][]string{
		{"  /me:", "  /members/{membership_id}:", "  /appointments:"},
		{"- name: identity", "- name: appointments"},
		{"    Me:", "    Problem:", "    Appointment:"},
	} {
		last := -1
		for _, want := range order {
			i := strings.Index(s, want)
			if i <= last {
				t.Errorf("%q is missing or out of order in:\n%s", want, s)
			}
			last = i
		}
	}
	if strings.Contains(s, "core.yaml#") {
		t.Errorf("core references must be rewritten as local ones:\n%s", s)
	}
	doc := decode(t, out)
	if doc["info"].(map[string]any)["title"] != "Core" { //nolint:forcetypeassert // a wrong shape fails the test anyway
		t.Errorf("info must be the core's: %v", doc["info"])
	}
	if !strings.Contains(s, `$ref: "#/components/responses/InternalError"`) || !strings.Contains(s, "  parameters:\n    Page:") {
		t.Errorf("app references and sections are missing:\n%s", s)
	}
}

func TestMerge_Deterministic(t *testing.T) {
	t.Parallel()

	first, err := mergeStrings(t, appSpec, modules())
	if err != nil {
		t.Fatal(err)
	}
	for range 5 {
		again, err := mergeStrings(t, appSpec, modules())
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(first, again) {
			t.Fatalf("two merges differ:\n%s\n---\n%s", first, again)
		}
	}
}

// emptyApp is the template's app.yaml in essence: no paths, tags or components.
const emptyApp = "openapi: 3.1.0\ninfo: {title: App, version: 0.1.0}\npaths: {}\n"

func TestMerge_EmptyAppIsTheCore(t *testing.T) {
	t.Parallel()

	out, err := mergeStrings(t, emptyApp, modules()[:1])
	if err != nil {
		t.Fatal(err)
	}
	if got, want := decode(t, out), decode(t, []byte(coreSpec)); !reflect.DeepEqual(got, want) {
		t.Fatalf("merged = %v\nwant the core contract %v", got, want)
	}
}

func TestMerge_Refuses(t *testing.T) {
	t.Parallel()

	// app returns appSpec with old replaced by repl; old must occur in it.
	app := func(t *testing.T, old, repl string) string {
		t.Helper()
		if !strings.Contains(appSpec, old) {
			t.Fatalf("fixture lacks %q", old)
		}
		return strings.Replace(appSpec, old, repl, 1)
	}
	tests := []struct {
		name string
		app  func(*testing.T) string
		mods []module
		want []string
	}{
		{"core path", func(t *testing.T) string { return app(t, "  /appointments:", "  /me:") }, nil,
			[]string{"[contract-duplicate]", "path /me repeats core.yaml /me"}},
		{"path with other parameter names", func(t *testing.T) string { return app(t, "  /appointments:", "  /members/{id}:") }, nil,
			[]string{"[contract-duplicate]", "path /members/{id} repeats core.yaml /members/{membership_id}"}},
		{"operationId", func(t *testing.T) string { return app(t, "operationId: listAppointments", "operationId: getMe") }, nil,
			[]string{"[contract-duplicate]", `operationId "getMe" is already used by core.yaml`}},
		{"schema name", func(t *testing.T) string {
			return app(t, "    Appointment:\n", "    Appointment:\n      type: object\n    Me:\n")
		}, nil,
			[]string{"[contract-duplicate]", "components.schemas.Me already exists in core.yaml"}},
		{"response name", func(t *testing.T) string {
			return app(t, "  parameters:", "  responses:\n    InternalError: {description: mine}\n  parameters:")
		}, nil, []string{"[contract-duplicate]", "components.responses.InternalError already exists"}},
		{"core tag on an operation", func(t *testing.T) string { return app(t, "tags: [appointments]", "tags: [identity]") }, nil,
			[]string{"[contract-duplicate]", `GET /appointments: tag "identity" belongs to the core`}},
		{"core tag declared", func(t *testing.T) string {
			return app(t, "  - name: appointments", "  - name: appointments\n  - name: identity")
		}, nil,
			[]string{"[contract-duplicate]", `tag "identity" belongs to the core`}},
		{"tag without module", nil, modules()[:1],
			[]string{"[contract-module-key]", `tag "appointments" has no module: there is no api/app/modules/appointments/codegen.yaml`}},
		{"undeclared tag", func(t *testing.T) string { return app(t, "tags: [appointments]", "tags: [billing]") }, nil,
			[]string{"[contract-module-key]", `tag "billing" is not declared`, "api/app/modules/billing/codegen.yaml"}},
		{"two tags", func(t *testing.T) string { return app(t, "tags: [appointments]", "tags: [appointments, other]") }, nil,
			[]string{"[contract-module-key]", "tags is [appointments, other]; an operation has exactly one tag"}},
		{"no tag", func(t *testing.T) string { return app(t, "      tags: [appointments]\n", "") }, nil,
			[]string{"[contract-module-key]", "tags is []"}},
		{"module without operations", func(t *testing.T) string { return app(t, "tags: [appointments]", "tags: [billing]") },
			append(modules(), module{name: "billing", zone: zoneApp, config: "app/modules/billing/codegen.yaml"}),
			[]string{"[contract-module-key]", `app/modules/appointments/codegen.yaml: no operation has tag "appointments"`}},
		{"securitySchemes", func(t *testing.T) string {
			return app(t, "components:\n", "components:\n  securitySchemes:\n    tenant: {type: apiKey, in: header, name: X-Org}\n")
		}, nil,
			[]string{"[contract-core-owned]", "components.securitySchemes is defined in core.yaml"}},
		{"tenant header parameter", func(t *testing.T) string {
			return app(t, "Page: {name: page, in: query", "Page: {name: x-tenant-id, in: header")
		}, nil,
			[]string{"[contract-core-owned]", "a parameter redefines the X-Tenant-ID header"}},
		{"tenant header component", func(t *testing.T) string {
			return app(t, "  parameters:", "  headers:\n    X-Tenant-ID: {schema: {type: string}}\n  parameters:")
		}, nil,
			[]string{"[contract-core-owned]", "components.headers.X-Tenant-ID redefines the tenant header"}},
		{"root security", func(t *testing.T) string { return app(t, "tags:\n", "security: []\ntags:\n") }, nil,
			[]string{"[contract-core-owned]", `root member "security" is not allowed`}},
		{"openapi version", func(t *testing.T) string { return app(t, "openapi: 3.1.0", "openapi: 3.0.3") }, nil,
			[]string{"[contract-core-owned]", `openapi is "3.0.3", want "3.1.0"`}},
		{"operationId differing in case", func(t *testing.T) string { return app(t, "operationId: listAppointments", "operationId: GetMe") }, nil,
			[]string{"[contract-duplicate]", `operationId "GetMe" is already used by core.yaml`, "ignoring case"}},
		{"operationId differing in separators", func(t *testing.T) string {
			return app(t, "operationId: listAppointments", "operationId: remove_member")
		}, nil,
			[]string{"[contract-duplicate]", `operationId "remove_member" is already used by core.yaml`}},
		{"schema name differing in case", func(t *testing.T) string {
			return app(t, "    Appointment:\n", "    Appointment:\n      type: object\n    problem:\n")
		}, nil,
			[]string{"[contract-duplicate]", "components.schemas.problem collides with a name of the same section in core.yaml"}},
		{"two app schemas differing in case", func(t *testing.T) string {
			return app(t, "    Appointment:\n", "    appointment: {type: object}\n    Appointment:\n")
		}, nil,
			[]string{"[contract-duplicate]", "components.schemas.Appointment collides with a name of the same section in app.yaml"}},
		{"core path item reference", func(t *testing.T) string {
			return app(t, "  /appointments:\n", "  /demo/me:\n    $ref: \"core.yaml#/paths/~1me\"\n  /appointments:\n")
		}, nil,
			[]string{"[contract-core-owned]", `$ref "core.yaml#/paths/~1me": the app contract references only components`, "path /demo/me is a $ref"}},
		{"local path item reference", func(t *testing.T) string {
			return app(t, "  /appointments:\n", "  /demo/x:\n    $ref: \"#/components/pathItems/X\"\n  /appointments:\n") + "  pathItems:\n    X: {get: {operationId: x}}\n"
		}, nil, []string{"[contract-core-owned]", "path /demo/x is a $ref"}},
		{"local reference outside components", func(t *testing.T) string { return app(t, "#/components/schemas/Appointment", "#/paths/~1appointments") }, nil,
			[]string{"[contract-core-owned]", "references only components"}},
		{"dangling core reference", func(t *testing.T) string {
			return app(t, "core.yaml#/components/responses/InternalError", "core.yaml#/components/responses/Nope")
		}, nil, []string{"[contract-core-owned]", "core.yaml has no #/components/responses/Nope"}},
		{"dangling local reference", func(t *testing.T) string {
			return app(t, "#/components/schemas/Appointment", "#/components/schemas/Problem")
		}, nil,
			[]string{"[contract-core-owned]", "is referenced as core.yaml#/components/schemas/Problem"}},
		{"other external reference", func(t *testing.T) string {
			return app(t, "#/components/schemas/Appointment", "other.yaml#/components/schemas/X")
		}, nil,
			[]string{"[contract-core-owned]", `$ref "other.yaml#/components/schemas/X"`}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			spec := appSpec
			if tc.app != nil {
				spec = tc.app(t)
			}
			mods := tc.mods
			if mods == nil {
				mods = modules()
			}
			_, err := mergeStrings(t, spec, mods)
			if err == nil {
				t.Fatal("merge succeeded, want an error")
			}
			for _, want := range tc.want {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("error %q\nwant it to contain %q", err, want)
				}
			}
		})
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func codegen(pkg, output string, tags ...string) string {
	return "package: " + pkg + "\noutput: " + output + "\noutput-options:\n  include-tags: [" + strings.Join(tags, ", ") + "]\n"
}

func TestDiscoverModules(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	writeFile(t, filepath.Join(root, "core/identity/codegen.yaml"), codegen("identityapi", "gen/openapi/identity/identity.gen.go", "identity"))
	writeFile(t, filepath.Join(root, "core/health/codegen.yaml"), codegen("healthapi", "gen/openapi/health/health.gen.go", "health"))
	writeFile(t, filepath.Join(root, "core/kit/config/x.go"), "package config\n")
	writeFile(t, filepath.Join(root, "app/modules/appointments/codegen.yaml"), codegen("appointmentsapi", "gen/openapi/appointments/appointments.gen.go", "appointments"))

	mods, err := discoverModules(root)
	if err != nil {
		t.Fatal(err)
	}
	want := []module{
		{name: "health", zone: zoneCore, config: "core/health/codegen.yaml"},
		{name: "identity", zone: zoneCore, config: "core/identity/codegen.yaml"},
		{name: "appointments", zone: zoneApp, config: "app/modules/appointments/codegen.yaml"},
	}
	if !reflect.DeepEqual(mods, want) {
		t.Fatalf("modules = %+v, want %+v", mods, want)
	}
}

func TestDiscoverModules_Refuses(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"include-tags is not the folder", map[string]string{
			"app/modules/demo/codegen.yaml": codegen("demoapi", "gen/openapi/demo/demo.gen.go", "identity"),
		}, "app/modules/demo/codegen.yaml: output-options.include-tags is [identity], want [demo]"},
		{"two include-tags", map[string]string{
			"app/modules/demo/codegen.yaml": codegen("demoapi", "gen/openapi/demo/demo.gen.go", "demo", "other"),
		}, "include-tags is [demo other], want [demo]"},
		{"package", map[string]string{
			"app/modules/demo/codegen.yaml": codegen("demo", "gen/openapi/demo/demo.gen.go", "demo"),
		}, `package is "demo", want "demoapi"`},
		{"output", map[string]string{
			"app/modules/demo/codegen.yaml": codegen("demoapi", "gen/openapi/other/demo.gen.go", "demo"),
		}, `output is "gen/openapi/other/demo.gen.go", want "gen/openapi/demo/demo.gen.go"`},
		{"folder name", map[string]string{
			"app/modules/Demo-x/codegen.yaml": codegen("Demo-xapi", "gen/openapi/Demo-x/Demo-x.gen.go", "Demo-x"),
		}, "must match [a-z][a-z0-9]*"},
		{"same name in both zones", map[string]string{
			"core/identity/codegen.yaml":        codegen("identityapi", "gen/openapi/identity/identity.gen.go", "identity"),
			"app/modules/identity/codegen.yaml": codegen("identityapi", "gen/openapi/identity/identity.gen.go", "identity"),
		}, `two modules are named "identity"`},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			for p, c := range tc.files {
				writeFile(t, filepath.Join(root, p), c)
			}
			_, err := discoverModules(root)
			if err == nil || !strings.Contains(err.Error(), tc.want) || !strings.Contains(err.Error(), "[contract-module-key]") {
				t.Fatalf("discoverModules = %v, want a [contract-module-key] error containing %q", err, tc.want)
			}
		})
	}
}

// TestRun_Repository merges the real contracts with the real modules: the template's
// empty app.yaml must reproduce core.yaml, twice the same bytes.
func TestRun_Repository(t *testing.T) {
	t.Parallel()

	out := filepath.Join(t.TempDir(), "a.yaml")
	again := filepath.Join(t.TempDir(), "b.yaml")
	for _, o := range []string{out, again} {
		if err := run("../../../api-spec/core.yaml", "../../../api-spec/app.yaml", "../..", o); err != nil {
			t.Fatal(err)
		}
	}
	a, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(again)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("two runs wrote different files")
	}
	core, err := os.ReadFile("../../../api-spec/core.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(decode(t, a), decode(t, core)) {
		t.Fatal("with the template's app.yaml the merged contract must equal core.yaml")
	}
}
