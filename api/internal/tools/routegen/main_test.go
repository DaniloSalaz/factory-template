package main

import (
	"slices"
	"strings"
	"testing"
)

const header = `
openapi: 3.1.0
security:
  - session: []
    tenant: []
components:
  securitySchemes:
    session: {type: apiKey, in: cookie, name: s}
    tenant: {type: apiKey, in: header, name: X-Tenant-ID}
`

func TestParse(t *testing.T) {
	t.Parallel()

	routes, err := parse([]byte(header + `
paths:
  /members/{membership_id}:
    parameters:
      - {name: membership_id, in: path, required: true, schema: {type: string}}
    patch:
      summary: undeclared, so the root default applies
  /me:
    get:
      security:
        - session: []
  /healthz:
    get:
      security: []
`))
	if err != nil {
		t.Fatal(err)
	}
	want := []route{
		{pattern: "GET /healthz"},
		{pattern: "GET /me", session: true},
		{pattern: "PATCH /members/{membership_id}", session: true, tenant: true},
	}
	if len(routes) != len(want) {
		t.Fatalf("routes = %+v, want %+v", routes, want)
	}
	for i := range want {
		if routes[i].pattern != want[i].pattern || routes[i].session != want[i].session || routes[i].tenant != want[i].tenant {
			t.Errorf("route %d = %+v, want %+v", i, routes[i], want[i])
		}
	}
}

func TestParse_Refuses(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		spec string
		want string
	}{
		{"no root default", `
openapi: 3.1.0
components: {securitySchemes: {session: {}, tenant: {}}}
paths: {}`, "root `security`"},
		{"missing scheme", `
openapi: 3.1.0
security: []
components: {securitySchemes: {session: {}}}
paths: {}`, "securitySchemes.tenant"},
		{"alternatives", header + `
paths: {/x: {get: {security: [{session: []}, {tenant: []}]}}}`, "alternative"},
		{"unknown scheme", header + `
paths: {/x: {get: {security: [{bearer: []}]}}}`, "unknown security scheme"},
		{"tenant without session", header + `
paths: {/x: {get: {security: [{tenant: []}]}}}`, "requires a session"},
		{"optional marker", header + `
paths: {/x: {get: {security: [{}]}}}`, "ambiguous"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			if _, err := parse([]byte(tc.spec)); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("parse = %v, want an error containing %q", err, tc.want)
			}
		})
	}
}

func TestRender(t *testing.T) {
	t.Parallel()

	src, err := render([]route{{pattern: "GET /me", session: true}})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), `"GET /me": {Session: true, Tenant: false},`) ||
		!strings.HasPrefix(string(src), "// Code generated by routegen") {
		t.Fatalf("unexpected output:\n%s", src)
	}
}

func TestParse_BodyFields(t *testing.T) {
	t.Parallel()

	routes, err := parse([]byte(header + `
  schemas:
    Strict:
      type: object
      additionalProperties: false
      properties: {name: {type: string}, slug: {type: string}}
    Open:
      type: object
      properties: {name: {type: string}}
paths:
  /ref:
    post:
      requestBody: {content: {application/json: {schema: {$ref: "#/components/schemas/Strict"}}}}
  /inline:
    post:
      requestBody:
        content:
          application/json:
            schema: {type: object, additionalProperties: false, properties: {role: {type: string}}}
  /open:
    post:
      requestBody: {content: {application/json: {schema: {$ref: "#/components/schemas/Open"}}}}
  /typed-extra:
    post:
      requestBody:
        content:
          application/json:
            schema: {type: object, additionalProperties: {type: string}, properties: {a: {type: string}}}
  /nobody:
    get: {}
`))
	if err != nil {
		t.Fatal(err)
	}
	got := map[string][]string{}
	for _, r := range routes {
		got[r.pattern] = r.fields
	}
	want := map[string][]string{
		"POST /ref": {"name", "slug"}, "POST /inline": {"role"},
		"POST /open": nil, "POST /typed-extra": nil, "GET /nobody": nil,
	}
	for pattern, fields := range want {
		if !slices.Equal(got[pattern], fields) || (fields == nil) != (got[pattern] == nil) {
			t.Errorf("%s fields = %v, want %v", pattern, got[pattern], fields)
		}
	}

	if _, err := parse([]byte(header + `
paths:
  /x:
    post:
      requestBody: {content: {application/json: {schema: {$ref: "#/components/schemas/Missing"}}}}
`)); err == nil || !strings.Contains(err.Error(), "Missing") {
		t.Fatalf("a dangling $ref: %v, want an error naming it", err)
	}
}

func TestRender_BodyFields(t *testing.T) {
	t.Parallel()

	src, err := render([]route{{pattern: "PATCH /tenant", session: true, tenant: true, fields: []string{"name"}}, {pattern: "GET /me", session: true}})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), `"PATCH /tenant": {"name"},`) || strings.Contains(string(src), `"GET /me": {}`) {
		t.Fatalf("unexpected output:\n%s", src)
	}
}
